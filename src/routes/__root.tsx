import { Outlet, createRootRoute, useRouter, HeadContent, Scripts } from "@tanstack/react-router";
import type { ReactNode } from "react";

import appCss from "../styles.css?url";
import { NotFoundPage } from "@/components/site/not-found-page";

function ErrorComponent({ error, reset }: { error: Error; reset: () => void }) {
  console.error(error);
  const router = useRouter();

  return (
    <main className="flex min-h-screen items-center justify-center bg-background px-4 text-foreground">
      <div className="max-w-md text-center">
        <h1 className="font-display text-3xl uppercase">This page didn't load</h1>
        <p className="mt-2 text-sm text-foreground/70">
          Something went wrong on our end. You can try refreshing or head back home.
        </p>
        <div className="mt-6 flex flex-wrap justify-center gap-2">
          <button
            onClick={() => {
              router.invalidate();
              reset();
            }}
            className="site-button bg-primary text-primary-foreground hover:bg-primary/85"
          >
            Try again
          </button>
          <a href="/" className="site-button site-button-outline">
            Go home
          </a>
        </div>
      </div>
    </main>
  );
}

